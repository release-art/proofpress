"""The PDF/X standards, one rule at a time, organised the way the standard is.

Every PDF/X rule lives here, in a table per flavour (:mod:`.x1a`, :mod:`.x3`, :mod:`.x4`), so completing the standard
means filling rows in. Colour *policy* (RGB against CMYK, ink limits, profile consistency, spot allowlists) is not a
PDF/X rule and stays in :mod:`..colour`. :func:`coverage_markdown` is the table of what is checked, kept in
``COVERAGE.md`` by ``python -m proof_pdf._internal.pdfx`` and checked by a test.
"""

import pathlib

import pikepdf

from ...models import Finding, PdfxVersion, Severity
from . import x1a, x3, x4
from .rule import IMPLEMENTED, PARTIAL, TODO, UNSOURCED, Rule

__all__ = ["FLAVOURS", "Rule", "check", "coverage_markdown", "rules"]

_TABLES = {"x1a": x1a.RULES, "x3": x3.RULES, "x4": x4.RULES}
FLAVOURS = tuple(v.value for v in PdfxVersion)
COVERAGE = pathlib.Path(__file__).with_name("COVERAGE.md")


def rules(flavour: str) -> tuple[Rule, ...]:
    """The rule table of a flavour (``x1a``, ``x3`` or ``x4``)."""
    return _TABLES[flavour]


def check(pdf: pikepdf.Pdf, flavour: str) -> list[Finding]:
    """Run every implemented or partial rule of *flavour*.

    A flavour with no rule implemented cannot confirm anything, so it fails with one finding saying so rather than
    passing silently.
    """
    table = rules(flavour)
    runnable = [r for r in table if r.check is not None]
    if not runnable:
        missing = sum(r.status == TODO for r in table)
        return [
            Finding(
                "pdfx-coverage",
                Severity.ERROR,
                f"PDF/X-{flavour[1:]} cannot be confirmed: none of its {missing} rules is implemented yet "
                "(see pdfx/COVERAGE.md)",
            )
        ]
    return [finding for rule in runnable if rule.check is not None for finding in rule.check(pdf)]


def coverage_markdown() -> str:
    """The coverage table, as ``COVERAGE.md`` holds it."""
    lines = [
        "# PDF/X coverage",
        "",
        "Generated by `python -m proof_pdf._internal.pdfx`; a test fails when it is stale.",
        "`unsourced` means the clause is not yet matched to the standard's text: none is ever written from memory.",
        "The summaries of `todo` rows paraphrase the owner's brief, not the standard.",
        "",
    ]
    for flavour, table in _TABLES.items():
        counts = {s: sum(r.status == s for r in table) for s in (IMPLEMENTED, PARTIAL, TODO)}
        lines += [
            f"## {flavour}: {counts[IMPLEMENTED]} implemented, {counts[PARTIAL]} partial, {counts[TODO]} todo",
            "",
            "| rule | part | clause | status | summary |",
            "| --- | --- | --- | --- | --- |",
        ]
        lines += [f"| {r.id} | {r.part} | {r.clause} | {r.status} | {r.summary} |" for r in table]
        lines.append("")
    return "\n".join(lines)

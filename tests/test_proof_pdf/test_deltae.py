@pytest.mark.parametrize(("lab1", "lab2", "expected"), SHARMA)
def test_matches_the_published_reference(lab1, lab2, expected):
    assert ciede2000(lab1, lab2) == pytest.approx(expected, abs=1e-4)


def test_is_symmetric():
    for lab1, lab2, _ in SHARMA:
        assert ciede2000(lab1, lab2) == pytest.approx(ciede2000(lab2, lab1), abs=1e-9)


def test_identical_colours_do_not_differ():
    assert ciede2000((50.0, 10.0, -20.0), (50.0, 10.0, -20.0)) == 0.0
